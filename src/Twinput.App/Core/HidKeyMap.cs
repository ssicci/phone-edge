namespace Twinput.App.Core;

/// <summary>Windows 스캔코드(세트 1) → HID usage (Keyboard 페이지 0x07). 수정키는 0xE0~0xE7.</summary>
public static class HidKeyMap
{
    public const byte LCtrl = 0xE0, LShift = 0xE1, LAlt = 0xE2, LGui = 0xE3,
                      RCtrl = 0xE4, RShift = 0xE5, RAlt = 0xE6, RGui = 0xE7;
    public const byte Lang1 = 0x90, Lang2 = 0x91, Escape = 0x29;

    private const int VkHangul = 0x15, VkHanja = 0x19, VkPause = 0x13;

    private static readonly byte[] Normal = new byte[0x100];
    private static readonly byte[] Extended = new byte[0x100];

    static HidKeyMap()
    {
        // 숫자열 1~9, 0
        for (int i = 0; i < 10; i++) Normal[0x02 + i] = (byte)(0x1E + i);
        Fill(0x10, 0x14, 0x1A, 0x08, 0x15, 0x17, 0x1C, 0x18, 0x0C, 0x12, 0x13);      // Q W E R T Y U I O P
        Fill(0x1E, 0x04, 0x16, 0x07, 0x09, 0x0A, 0x0B, 0x0D, 0x0E, 0x0F);             // A S D F G H J K L
        Fill(0x2C, 0x1D, 0x1B, 0x06, 0x19, 0x05, 0x11, 0x10);                         // Z X C V B N M
        Fill(0x3B, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43);       // F1~F10
        Fill(0x47, 0x5F, 0x60, 0x61, 0x56, 0x5C, 0x5D, 0x5E, 0x57, 0x59, 0x5A, 0x5B, 0x62, 0x63); // 키패드 7 8 9 - 4 5 6 + 1 2 3 0 .

        Normal[0x01] = 0x29; // Esc
        Normal[0x0C] = 0x2D; Normal[0x0D] = 0x2E; Normal[0x0E] = 0x2A; Normal[0x0F] = 0x2B;
        Normal[0x1A] = 0x2F; Normal[0x1B] = 0x30; Normal[0x1C] = 0x28;
        Normal[0x27] = 0x33; Normal[0x28] = 0x34; Normal[0x29] = 0x35; Normal[0x2B] = 0x31;
        Normal[0x33] = 0x36; Normal[0x34] = 0x37; Normal[0x35] = 0x38;
        Normal[0x37] = 0x55; Normal[0x39] = 0x2C; Normal[0x3A] = 0x39;
        Normal[0x45] = 0x53; Normal[0x46] = 0x47;
        Normal[0x56] = 0x64; Normal[0x57] = 0x44; Normal[0x58] = 0x45;
        Normal[0x1D] = LCtrl; Normal[0x2A] = LShift; Normal[0x36] = RShift; Normal[0x38] = LAlt;
        Normal[0xF2] = Lang1; Normal[0xF1] = Lang2; // 한국어 키보드 한/영, 한자

        Extended[0x1C] = 0x58; Extended[0x35] = 0x54; Extended[0x37] = 0x46; // KP Enter, KP /, PrintScreen
        Extended[0x1D] = RCtrl; Extended[0x38] = RAlt; Extended[0x5B] = LGui; Extended[0x5C] = RGui;
        Extended[0x5D] = 0x65; // Menu
        Extended[0x47] = 0x4A; Extended[0x48] = 0x52; Extended[0x49] = 0x4B;
        Extended[0x4B] = 0x50; Extended[0x4D] = 0x4F;
        Extended[0x4F] = 0x4D; Extended[0x50] = 0x51; Extended[0x51] = 0x4E;
        Extended[0x52] = 0x49; Extended[0x53] = 0x4C;
        Extended[0x45] = 0x53; // NumLock (확장 표기로 오는 경우)
    }

    private static void Fill(int firstScan, params byte[] usages)
    {
        for (int i = 0; i < usages.Length; i++) Normal[firstScan + i] = usages[i];
    }

    /// <summary>알 수 없는 키는 0. 한/영·한자·Pause 는 가상 키 코드로 먼저 판별한다.</summary>
    public static byte Resolve(int vkCode, int scanCode, bool extended)
    {
        switch (vkCode)
        {
            case VkHangul: return Lang1;
            case VkHanja: return Lang2;
            case VkPause: return 0x48;
        }
        scanCode &= 0xFF;
        return extended ? Extended[scanCode] : Normal[scanCode];
    }
}
